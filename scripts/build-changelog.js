'use strict';
// Builds docs/changelog.html (the website's release-notes page) from CHANGELOG.md.
// The site has no build step, so run this after editing CHANGELOG.md and commit the result:
//   node scripts/build-changelog.js
const fs = require('fs');
const path = require('path');
const { marked } = require('marked');

const ROOT = path.resolve(__dirname, '..');
const REPO = 'https://github.com/QuangquyNguyenvo/Sameko-Dev-CPP';
const md = fs.readFileSync(path.join(ROOT, 'CHANGELOG.md'), 'utf8').replace(/\r\n/g, '\n');
const home = fs.readFileSync(path.join(ROOT, 'docs', 'index.html'), 'utf8').replace(/\r\n/g, '\n');

const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const cut = (src, a, b) => { const i = src.indexOf(a); const j = src.indexOf(b, i); if (i < 0 || j < 0) throw new Error('index.html: missing ' + a); return src.slice(i, j + b.length); };

// "#70" and "@name" become links, except inside `code`.
function linkRefs(text) {
    return text.split('`').map((part, i) => (i % 2 ? part : part
        .replace(/(^|[\s(,])#(\d+)\b/g, (m, pre, n) => `${pre}[#${n}](${REPO}/issues/${n})`)
        .replace(/(^|[\s(,])@([A-Za-z0-9][A-Za-z0-9-]{1,38})\b/g, (m, pre, u) => `${pre}[@${u}](https://github.com/${u})`))).join('`');
}
const render = (text) => marked.parse(linkRefs(text.trim()), { gfm: true })
    .replace(/<a href="http/g, '<a target="_blank" rel="noopener" href="http');

const KINDS = { added: 'added', changed: 'changed', fixed: 'fixed', security: 'security', performance: 'perf', removed: 'removed', deprecated: 'removed' };
const releases = md.split(/^## (?=\[)/m).slice(1).map((block) => {
    const nl = block.indexOf('\n');
    const head = /^\[(.+?)\](?:\s*-\s*(\d{4}-\d{2}-\d{2}))?/.exec(block.slice(0, nl));
    if (!head) throw new Error('unreadable release heading: ' + block.slice(0, nl));
    const parts = block.slice(nl + 1).split(/^### /m);
    const sections = parts.slice(1).map((p) => {
        const end = p.indexOf('\n');
        const title = p.slice(0, end).trim();
        const word = title.replace(/[^A-Za-z ]/g, '').trim().split(' ')[0].toLowerCase();
        return { title, kind: KINDS[word] || 'other', html: render(p.slice(end + 1)) };
    });
    return { version: head[1], date: head[2] || '', id: 'v' + head[1].replace(/[^0-9A-Za-z]+/g, '-'), intro: parts[0].trim() ? render(parts[0]) : '', sections };
});
if (!releases.length) throw new Error('no releases found in CHANGELOG.md');

const fmtDate = (d) => (d ? new Date(d + 'T00:00:00Z').toLocaleDateString('en-GB', { day: 'numeric', month: 'long', year: 'numeric', timeZone: 'UTC' }) : '');
const latest = releases[0];
const TITLE = 'Changelog | Sameko Dev C++ Release Notes';
const DESC = `Every Sameko Dev C++ release, newest first: what was added, changed and fixed in each version. Latest: ${latest.version}, released ${fmtDate(latest.date)}.`;
const footer = cut(home, '<footer class="foot">', '</footer>').split('href="#').join('href="./#');

const ld = { '@context': 'https://schema.org', '@graph': [
    { '@type': 'WebPage', '@id': 'https://sameko.dev/changelog#page', url: 'https://sameko.dev/changelog', name: TITLE, description: DESC, inLanguage: 'en',
      isPartOf: { '@id': 'https://sameko.dev/#website' }, about: { '@id': 'https://sameko.dev/#software' }, dateModified: latest.date },
    { '@type': 'BreadcrumbList', itemListElement: [
        { '@type': 'ListItem', position: 1, name: 'Sameko Dev C++', item: 'https://sameko.dev/' },
        { '@type': 'ListItem', position: 2, name: 'Changelog', item: 'https://sameko.dev/changelog' } ] },
] };

const article = (r, i) => `
                    <article class="rel${i === 0 ? ' rel--latest' : ''}" id="${r.id}">
                        <header class="rel__head">
                            <h2 class="rel__version"><a href="#${r.id}">${esc(r.version)}</a></h2>
                            ${i === 0 ? '<span class="rel__tag">Latest</span>' : ''}
                            ${r.date ? `<time class="rel__date" datetime="${r.date}">${fmtDate(r.date)}</time>` : ''}
                            <a class="rel__gh" href="${REPO}/releases/tag/v${esc(r.version)}" target="_blank" rel="noopener">Downloads on GitHub</a>
                        </header>
                        ${r.intro ? `<div class="rel__intro">${r.intro}</div>` : ''}
${r.sections.map((s) => `                        <section class="rel__sec rel__sec--${s.kind}">
                            <h3><span class="rel__chip">${esc(s.title)}</span></h3>
                            ${s.html}
                        </section>`).join('\n')}
                    </article>`;

const html = `<!DOCTYPE html>
<!-- Generated by scripts/build-changelog.js from CHANGELOG.md. Do not edit by hand. -->
<html lang="en">

<head>
    <meta charset="UTF-8">
    <meta name="viewport" content="width=device-width, initial-scale=1.0">
    <script src="assets/js/theme-init.js"></script>
    <link rel="stylesheet" href="assets/css/fonts.css">
    <title>${esc(TITLE)}</title>
    <meta name="description" content="${esc(DESC)}">
    <meta name="author" content="QuangquyNguyenvo">
    <meta name="theme-color" content="#88c9ea">
    <meta name="robots" content="index, follow">
    <link rel="icon" href="assets/favicon-32.png" sizes="32x32">
    <link rel="icon" href="assets/logo-48.png" sizes="48x48">
    <link rel="apple-touch-icon" href="assets/icon-192.png">
    <link rel="canonical" href="https://sameko.dev/changelog">
    <meta property="og:type" content="article">
    <meta property="og:url" content="https://sameko.dev/changelog">
    <meta property="og:title" content="${esc(TITLE)}">
    <meta property="og:description" content="${esc(DESC)}">
    <meta property="og:image" content="https://sameko.dev/assets/og-image.png">
    <meta property="og:image:width" content="1200">
    <meta property="og:image:height" content="630">
    <meta property="og:site_name" content="Sameko Dev C++">
    <meta name="twitter:card" content="summary_large_image">
    <meta name="twitter:title" content="${esc(TITLE)}">
    <meta name="twitter:description" content="${esc(DESC)}">
    <meta name="twitter:image" content="https://sameko.dev/assets/og-image.png">
    <script type="application/ld+json">
${JSON.stringify(ld, null, 2)}
    </script>
    <link rel="stylesheet" href="assets/css/tokens.css">
    <link rel="stylesheet" href="assets/css/home.css">
    <link rel="stylesheet" href="assets/css/homepage.css">
    <link rel="stylesheet" href="assets/css/changelog.css">
</head>

<body class="sameko-home changelog-page">
    <a class="skip-link" href="#main">Skip to content</a>

    <nav class="nav">
        <div class="wrap nav__inner">
            <a class="nav__brand" href="./" aria-label="Sameko Dev C++ home">
                <img src="assets/logo-48.png" alt="" width="32" height="32">
                <span>Sameko Dev C++</span>
            </a>
            <div class="nav__links">
                <a href="./#features">Features</a>
                <a href="./#comparison">Compare</a>
                <a href="wiki.html">Wiki</a>
                <a href="changelog.html" aria-current="page">Changelog</a>
            </div>
            <div class="nav__actions">
                <a class="btn btn--primary" href="./#download-trigger">Download</a>
            </div>
        </div>
    </nav>

    <main id="main">
        <header class="band log-hero">
            <div class="log-hero__art" aria-hidden="true">
                <span class="log-hero__word">v${esc(latest.version.split('.').slice(0, 2).join('.'))}</span>
                <span class="shape shape--circle" style="--x:6%;--y:22%;--sz:44px;--c:var(--shape-sky);--d:7s"></span>
                <span class="shape shape--ring" style="--x:44%;--y:84%;--sz:36px;--c:var(--shape-butter);--d:10s"></span>
                <span class="shape shape--pill" style="--x:86%;--y:70%;--sz:70px;--c:var(--shape-white);--d:8s;--r:-14deg"></span>
                <span class="shape shape--squircle" style="--x:92%;--y:20%;--sz:38px;--c:var(--shape-butter);--d:9.5s;--r:18deg"></span>
            </div>
            <div class="wrap">
                <div class="band__head">
                    <span class="eyebrow">Changelog</span>
                    <h1 class="h-display">What changed, <span class="hl">and when.</span></h1>
                    <p class="lede">Every version of Sameko Dev C++, newest first. The latest is <a href="#${latest.id}">${esc(latest.version)}</a>, released ${fmtDate(latest.date)}.</p>
                </div>
            </div>
        </header>

        <section class="band band--alt log-body">
            <div class="wrap log">
                <aside class="log__nav" aria-label="Versions">
                    <p class="log__nav-title">Versions</p>
                    <ol>
${releases.map((r, i) => `                        <li><a href="#${r.id}"><b>${esc(r.version)}</b>${i === 0 ? '<i>Latest</i>' : ''}<span>${r.date ? r.date.slice(0, 7) : ''}</span></a></li>`).join('\n')}
                    </ol>
                </aside>
                <div class="log__list">${releases.map(article).join('\n')}
                </div>
            </div>
        </section>

        <section id="cta" class="band band--cta">
            <div class="wrap cta">
                <h2 class="h-section">Get the latest build.</h2>
                <p class="lede">The installer updates itself. The portable zip is one download away.</p>
                <div class="cta__actions">
                    <a href="./#download-trigger" class="btn btn--primary btn--lg">Download ${esc(latest.version)}</a>
                    <a href="${REPO}/releases" target="_blank" rel="noopener" class="btn btn--ghost btn--lg">All releases on GitHub</a>
                </div>
            </div>
        </section>
    </main>

    ${footer}
</body>

</html>
`;
fs.writeFileSync(path.join(ROOT, 'docs', 'changelog.html'), html);
console.log(`docs/changelog.html: ${releases.length} releases, latest ${latest.version} (${latest.date}), ${Math.round(html.length / 1024)} KB`);
