'use strict';
/**
 * Keeps the bundled GCC out of the app package of the Windows installer, so an update that does
 * not change the toolchain does not delete and rewrite its ~4,800 files (~700 MB): that took
 * about a minute, while the app itself is ~20 files.
 *
 * electron-builder `afterPack` hook (package.json › build.afterPack). It does something only when
 * SAMEKO_SPLIT_TOOLCHAIN=1, which scripts/build-win.js sets for the NSIS build:
 *   1. names the toolchain by its content: gcc-<version>-<12 hex of a hash of every file>;
 *   2. packs resources/Sameko-GCC into build/toolchain/<id>.7z, once per id (the same bytes in
 *      every installer, so electron-updater's differential download skips them);
 *   3. writes build/toolchain/toolchain.nsh with that id and path, which installer/installer.nsh
 *      includes: the installer extracts the archive only when the installed toolchain's
 *      .sameko-toolchain stamp differs, and the uninstaller keeps the toolchain on an update;
 *   4. moves resources/Sameko-GCC out of the app folder (to <appOutDir>.Sameko-GCC), so it is
 *      not in the app package. scripts/build-win.js moves it back after the build.
 * The zip target is built in a run without the variable and keeps the toolchain in place.
 *
 * SAMEKO_TOOLCHAIN_ID_SUFFIX=<text> appends to the id (to test an update that changes it).
 */

const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const { execFileSync } = require('child_process');

const ROOT = path.join(__dirname, '..');
const OUT = path.join(ROOT, 'build', 'toolchain');
const NSH = path.join(OUT, 'toolchain.nsh');

function* files(dir, rel = '') {
    const entries = fs.readdirSync(path.join(dir, rel), { withFileTypes: true })
        .sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0));
    for (const e of entries) {
        const r = rel ? `${rel}/${e.name}` : e.name;
        if (e.isDirectory()) yield* files(dir, r);
        else yield r;
    }
}

/** gcc-<version>-<hash of every path and content>, the same for the same files. */
function toolchainId(dir) {
    const hash = crypto.createHash('sha256');
    for (const rel of files(dir)) {
        if (rel === '.sameko-toolchain') continue;
        hash.update(rel + '\0');
        hash.update(fs.readFileSync(path.join(dir, rel)));
        hash.update('\0');
    }
    const libgcc = path.join(dir, 'lib', 'gcc');
    let version = 'unknown';
    if (fs.existsSync(libgcc)) {
        for (const triplet of fs.readdirSync(libgcc)) {
            const v = fs.readdirSync(path.join(libgcc, triplet)).find((n) => /^\d+\.\d+/.test(n));
            if (v) { version = v; break; }
        }
    }
    const suffix = (process.env.SAMEKO_TOOLCHAIN_ID_SUFFIX || '').replace(/[^\w.-]/g, '');
    return `gcc-${version}-${hash.digest('hex').slice(0, 12)}${suffix ? `-${suffix}` : ''}`;
}

async function sevenZip() {
    const { getPath7za } = require('app-builder-lib/out/toolsets/7zip');
    return getPath7za();
}

async function packToolchain(dir) {
    const id = toolchainId(dir);
    fs.mkdirSync(OUT, { recursive: true });
    const archive = path.join(OUT, `${id}.7z`);
    if (fs.existsSync(archive)) {
        console.log(`  • toolchain ${id}: reusing ${path.relative(ROOT, archive)}`);
    } else {
        console.log(`  • toolchain ${id}: packing (once per toolchain, a few minutes)`);
        const partial = `${archive}.partial`;
        fs.rmSync(partial, { force: true });
        execFileSync(await sevenZip(), ['a', '-t7z', '-bd', '-mx=9', '-mtc=off', '-mtm=off', '-mta=off', partial, '.'],
            { cwd: dir, stdio: ['ignore', 'ignore', 'inherit'] });
        fs.renameSync(partial, archive);
    }
    // Old archives of other ids are left for the developer to delete (build/ is gitignored).
    fs.writeFileSync(NSH, [
        '; Generated by scripts/toolchain-package.js for this build; deleted afterwards.',
        `!define SAMEKO_TOOLCHAIN_ID "${id}"`,
        `!define SAMEKO_TOOLCHAIN_7Z "${archive}"`,
        '',
    ].join('\r\n'));
    return { id, archive };
}

/** Where the toolchain waits outside the app folder during the NSIS build. */
function stashOf(appOutDir) {
    return `${appOutDir}.Sameko-GCC`;
}

async function afterPack(context) {
    if (process.env.SAMEKO_SPLIT_TOOLCHAIN !== '1') return;
    if (context.electronPlatformName !== 'win32') return;
    const dir = path.join(context.appOutDir, 'resources', 'Sameko-GCC');
    if (!fs.existsSync(dir)) throw new Error(`toolchain-package: ${dir} not found`);
    await packToolchain(dir);
    const stash = stashOf(context.appOutDir);
    fs.rmSync(stash, { recursive: true, force: true });
    fs.renameSync(dir, stash);
}

/** Puts the toolchain back into the app folder and drops the generated .nsh. */
function restore(appOutDir) {
    const stash = stashOf(appOutDir);
    const dir = path.join(appOutDir, 'resources', 'Sameko-GCC');
    if (fs.existsSync(stash)) {
        fs.rmSync(dir, { recursive: true, force: true });
        fs.renameSync(stash, dir);
    }
    fs.rmSync(NSH, { force: true });
}

module.exports = afterPack;
module.exports.default = afterPack;
module.exports.restore = restore;
module.exports.toolchainId = toolchainId;
